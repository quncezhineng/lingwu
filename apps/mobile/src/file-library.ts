import { type FileKind, fileKind } from "./file-kind";
import type { TranslationKey } from "./i18n/locales/en";

type Dated = Pick<Artifact | AgentArtifact, "createdAt">;

function newestFirst<T extends Dated>(items: readonly T[]): T[] {
  return [...items].sort((a, b) => b.createdAt.localeCompare(a.createdAt));
}

/**
 * The Files page combines two persisted output types:
 * - files are imported PDFs, exported PDFs, and standalone HTML documents;
 * - artifacts are structured research outputs generated by agent tasks.
 */
export function buildFileLibrary(
  files: readonly Artifact[],
  artifacts: readonly AgentArtifact[],
): { files: Artifact[]; artifacts: AgentArtifact[] } {
  return {
    files: newestFirst(files),
    artifacts: newestFirst(artifacts),
  };
}

/**
 * 文件来源标签本地化：upload/analysis/export 映射为界面文案，
 * 未知来源回落原文（资料卡、搜索结果共用同一映射）。
 */
export function fileSourceLabel(source: string, t: (key: TranslationKey) => string) {
  const normalized = source.trim().toLowerCase();
  if (normalized === "upload" || normalized === "uploaded by you")
    return t("screens.filesSourceUpload");
  if (normalized === "analysis") return t("screens.filesSourceAnalysis");
  if (normalized === "export") return t("screens.filesSourceExport");
  return source;
}

export type FileSourceFilter = "all" | "analysis" | "upload";
export type FileFormatFilter = "all" | FileKind;

/** Uploaded-by-you files are separate from analysis, mail and browser-generated files. */
export function fileSourceBucket(file: Pick<Artifact, "source">): Exclude<FileSourceFilter, "all"> {
  const normalized = file.source.trim().toLowerCase();
  return normalized === "upload" || normalized === "uploaded by you" ? "upload" : "analysis";
}

/** Filtering stays pure so the page's empty state and counts can be tested directly. */
export function filterFileLibrary(
  files: readonly Artifact[],
  filters: {
    source: FileSourceFilter;
    format: FileFormatFilter;
    query: string;
  },
): Artifact[] {
  const query = filters.query.trim().toLowerCase();
  return files.filter((file) => {
    if (filters.source !== "all" && fileSourceBucket(file) !== filters.source) return false;
    if (filters.format !== "all" && fileKind(file) !== filters.format) return false;
    return !query || file.name.toLowerCase().includes(query);
  });
}

/** A short card preview should not expose Markdown control characters. */
export function markdownExcerpt(value: string, maxLength = 140): string {
  const text = value
    .replace(/```[\s\S]*?```/g, " ")
    .replace(/!\[([^\]]*)]\([^)]*\)/g, "$1")
    .replace(/\[([^\]]+)]\([^)]*\)/g, "$1")
    .replace(/<[^>]+>/g, " ")
    .replace(/^#{1,6}\s+/gm, "")
    .replace(/^\s*(?:[-*+]|\d+\.)\s+/gm, "")
    .replace(/[*`]/g, "")
    .replace(/\s+/g, " ")
    .trim();
  if (text.length <= maxLength) return text;
  return `${text.slice(0, maxLength).trimEnd()}…`;
}

/** 一个智能体名下的分析生成产物。 */
export interface AgentArtifactGroup {
  agentId: string;
  agentName: string;
  artifacts: AgentArtifact[];
}

/** 产物没有可追溯的智能体时统一归到这个分组，避免条目凭空消失。 */
export const UNASSIGNED_AGENT_ID = "unassigned";

/**
 * 把智能体生成的分析产物按「生成它的智能体」归类。
 *
 * 归属链路是 artifact.taskId → task.threadId → agent.threadId → agent：
 * AgentArtifact 本身只记任务 id，任务只在由对话发起时才带 threadId，
 * 因此后台定时任务（如市场简报）产出的结果会落到「未归属」分组。
 */
export function groupArtifactsByAgent(
  artifacts: readonly AgentArtifact[],
  tasks: readonly Pick<AgentTask, "id" | "threadId">[],
  agents: readonly Pick<AgentDefinition, "id" | "name" | "threadId">[],
  unassignedLabel: string,
): AgentArtifactGroup[] {
  const threadByTask = new Map(tasks.map((task) => [task.id, task.threadId]));
  const agentByThread = new Map(agents.map((agent) => [agent.threadId, agent]));
  const groups = new Map<string, AgentArtifactGroup>();
  for (const artifact of newestFirst(artifacts)) {
    const threadId = threadByTask.get(artifact.taskId);
    const owner = threadId ? agentByThread.get(threadId) : undefined;
    const agentId = owner?.id ?? UNASSIGNED_AGENT_ID;
    const group = groups.get(agentId) ?? {
      agentId,
      agentName: owner?.name ?? unassignedLabel,
      artifacts: [],
    };
    group.artifacts.push(artifact);
    groups.set(agentId, group);
  }
  // 已归属的智能体排在前面，同组内仍按时间倒序（newestFirst 已保证）。
  return [...groups.values()].sort((a, b) => {
    if (a.agentId === UNASSIGNED_AGENT_ID) return 1;
    if (b.agentId === UNASSIGNED_AGENT_ID) return -1;
    return 0;
  });
}

/** 产物标题匹配搜索词；格式筛选对产物不适用，由调用方决定是否展示。 */
export function filterArtifacts(
  artifacts: readonly AgentArtifact[],
  filters: { query: string },
): AgentArtifact[] {
  const query = filters.query.trim().toLowerCase();
  if (!query) return [...artifacts];
  return artifacts.filter((artifact) => artifact.title.toLowerCase().includes(query));
}
